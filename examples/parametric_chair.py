@dataclass
class Ctx:
    client: ToolClient
    discovery: Discovery
    args: argparse.Namespace
    warnings: list[str] = field(default_factory=list)

    @property
    def group_name(self) -> str:
        return GROUP_STEM + self.args.suffix

    @property
    def object_name(self) -> str:
        return OBJECT_STEM + self.args.suffix

    def warn(self, message: str) -> None:
        self.warnings.append(message)
        log(f"[warn] {message}")

    async def group_view(self) -> GroupView:
        payload = await self.client.call("blender_inspect_node_group", {"name": self.group_name})
        return build_group_view(payload)

    async def sockets(self, group: GroupView) -> Sockets:
        await self.discovery.describe_all()
        return Sockets(self.discovery, group)

    async def object_info(self) -> dict[str, Any]:
        return await self.client.call("blender_object_info", {"name": self.object_name})

    async def require_group(self) -> GroupView:
        return await self.group_view()

    async def require_object(self) -> dict[str, Any]:
        objects = await self.client.call(
            "blender_list_objects", {"name_contains": self.object_name, "limit": 200}
        )
        if not any(row.get("name") == self.object_name for row in objects.get("objects") or []):
            raise RecipeError(
                f"object {self.object_name!r} does not exist; run --phase seat first "
                f"(or pass the matching --suffix)"
            )
        return await self.object_info()

    async def assert_join_link_count(self, phase: str, *, exact: bool = True) -> int:
        """Prove that the join node really accumulated this phase's parts.

        ``exact=False`` is used after a phase was skipped as already-built: a later
        phase may have appended more parts since, so only a lower bound applies.
        """
        group = await self.require_group()
        sockets = await self.sockets(group)
        links = group.join_input_links(N_JOIN, sockets.join_geometry_in)
        expected = EXPECTED_JOIN_LINKS[phase]
        sources = ", ".join(str(link.get("from_node")) for link in links)
        satisfied = len(links) == expected if exact else len(links) >= expected
        if not satisfied:
            raise RecipeError(
                f"join node {N_JOIN!r} holds {len(links)} link(s) on its multi-input Geometry socket "
                f"after phase {phase!r}, expected "
                f"{'exactly ' if exact else 'at least '}{expected}. Appended parts: [{sources}]. The "
                f"multi-input socket did not accumulate the links the phase asked for - inspect the "
                f"group with blender_inspect_node_group before continuing."
            )
        log(f"[check] join {N_JOIN!r} multi-input links after {phase!r}: {len(links)}"
            f"{'/' if exact else '>='}{expected} "
            f"({sources})")
        return len(links)


def evaluated_bounds(object_info: dict[str, Any]) -> dict[str, Any]:
    bounds = (object_info.get("mesh") or {}).get("bounds")
    if not isinstance(bounds, dict) or not bounds.get("min") or not bounds.get("max"):
        raise RecipeError(
            "the object reports no evaluated world bounds; the Geometry Nodes modifier is probably "
            "muted or its output is not linked to Group Output"
        )
    return bounds


def modifier_parameters(object_info: dict[str, Any], group_name: str) -> dict[str, Any]:
    for modifier in object_info.get("modifiers") or []:
        if modifier.get("node_group") == group_name:
            return dict(modifier.get("parameters") or {})
    raise RecipeError(
        f"{object_info.get('name')!r} has no Geometry Nodes modifier using group {group_name!r}"
    )


def expected_bounds(params: dict[str, float]) -> dict[str, float]:
    """Closed-form world-space bounds of the chair this graph builds.

    Used by the verify phase to compare the evaluated geometry with the
    arithmetic the node graph is supposed to implement:

    * seat centre z = SeatHeight - SeatThickness/2, seat top = SeatHeight;
    * leg height = SeatHeight - SeatThickness, leg centres at
      +/-(SeatWidth - LegSize)/2 and +/-(SeatDepth - LegSize)/2, so the legs
      stand on z = 0 and reach the outermost x/y of the seat;
    * back post centre = (rear leg y, SeatHeight) + (BackHeight/2)*(sin, cos)
      of the tilt, with a -tilt X rotation. The post is a box of half extents
      (LegSize/2, LegSize/2, BackHeight/2), so its highest corner adds
      (BackHeight/2)*cos(tilt) + (LegSize/2)*sin(tilt) and its rearmost corner
      adds (BackHeight/2)*sin(tilt) + (LegSize/2)*cos(tilt) on top of the centre.

    With the defaults (Seat Width .48, Seat Depth .46, Seat Height .45,
    Seat Thickness .035, Leg Size .045, Back Height .42, Back Tilt .10,
    Rail Height .12) this predicts width 0.48, y in [-0.23, 0.271818] and
    z in [0, 0.870148] - the numbers the doc records for a hand check.
    """
    width = params["Seat Width"]
    depth = params["Seat Depth"]
    height = params["Seat Height"]
    leg = params["Leg Size"]
    back = params["Back Height"]
    tilt = params["Back Tilt"]

    leg_y = (depth - leg) / 2.0
    return {
        "min_x": -width / 2.0,
        "max_x": width / 2.0,
        "min_y": -(leg_y + leg / 2.0),
        "max_y": leg_y + back * math.sin(tilt) + (leg / 2.0) * math.cos(tilt),
        "min_z": 0.0,
        "max_z": height + back * math.cos(tilt) + (leg / 2.0) * math.sin(tilt),
    }


