# --------------------------------------------------------------------------- #
# MCP client: one typed tool call at a time, compact output, raise on isError
# --------------------------------------------------------------------------- #
def _compact(value: Any, limit: int = 220) -> str:
    """A short, single-line rendering of a value (never tool arguments' bulk)."""
    try:
        text = json.dumps(value, ensure_ascii=False, default=str)
    except (TypeError, ValueError):
        text = repr(value)
    text = re.sub(r"\s+", " ", text)
    if len(text) > limit:
        text = text[: limit - 3] + "..."
    return text


def _compact_args(arguments: dict[str, Any]) -> str:
    if isinstance(arguments.get("operations"), list):
        other = {k: v for k, v in arguments.items() if k != "operations"}
        return f"{_compact(other, 160)} operations=<{len(arguments['operations'])} ops>"
    return _compact(arguments)


def _text_blocks(result: Any) -> list[str]:
    blocks: list[str] = []
    for block in getattr(result, "content", None) or []:
        if getattr(block, "type", None) == "text":
            text = getattr(block, "text", "")
            if isinstance(text, str) and text.strip():
                blocks.append(text)
    return blocks


def _image_blocks(result: Any) -> list[Any]:
    return [b for b in (getattr(result, "content", None) or []) if getattr(b, "type", None) == "image"]


def parse_result(result: Any) -> dict[str, Any]:
    """Turn a CallToolResult into a payload dict (text JSON wins over structured)."""
    for text in reversed(_text_blocks(result)):
        stripped = text.strip()
        if stripped.startswith("{"):
            try:
                decoded = json.loads(stripped)
            except json.JSONDecodeError:
                continue
            if isinstance(decoded, dict):
                return decoded
    structured = getattr(result, "structuredContent", None)
    if isinstance(structured, dict):
        if set(structured) == {"result"} and isinstance(structured["result"], dict):
            return structured["result"]
        return structured
    return {}


def _error_detail(result: Any) -> str:
    blocks = _text_blocks(result)
    if blocks:
        return re.sub(r"\s+", " ", blocks[0]).strip()[:600]
    return "the tool reported isError without a text payload"


def summarize(tool: str, payload: dict[str, Any]) -> str:
    """One compact line describing what a tool actually did."""
    get = payload.get
    if tool == "blender_health":
        return (f"blender={get('blender_version')} scene={get('scene')!r} objects={get('objects')} "
                f"node_groups={get('node_groups')} blend={get('blend_filepath')!r}")
    if tool == "blender_scene_summary":
        return (f"scene={get('scene')!r} objects={get('objects_total')} "
                f"collections={len(get('collections') or [])} node_groups={len(get('node_groups') or [])}")
    if tool == "blender_list_objects":
        return f"count={get('count')}"
    if tool == "blender_list_node_types":
        return f"count={get('count')} truncated={get('truncated')}"
    if tool == "blender_describe_node_type":
        return (f"{get('node_type')} inputs={len(get('inputs') or [])} "
                f"outputs={len(get('outputs') or [])} properties={len(get('properties') or [])}")
    if tool == "blender_create_node_group":
        interface = (get("group") or {}).get("interface") or {}
        return (f"created={get('created')} reused={get('reused')} "
                f"iface_in={len(interface.get('inputs') or [])} iface_out={len(interface.get('outputs') or [])}")
    if tool == "blender_create_node":
        node = get("node") or {}
        return f"node={node.get('name')!r} type={node.get('bl_idname')}"
    if tool == "blender_inspect_node_group":
        interface = get("interface") or {}
        return (f"nodes={len(get('nodes') or [])} links={len(get('links') or [])} "
                f"iface_in={len(interface.get('inputs') or [])} users={get('users')}")
    if tool == "blender_batch_graph_edit":
        return (f"completed={get('completed_count')} failed={get('failed_count')} "
                f"committed={get('committed')} rolled_back={get('rolled_back')}")
    if tool == "blender_create_mesh_object":
        return (f"created={get('created')!r} vertices={get('vertices')} "
                f"collection={get('collection')!r} location={get('location')}")
    if tool == "blender_attach_geometry_nodes_modifier":
        evaluated = (get("evaluated") or {}).get("evaluated") or {}
        return (f"modifier={get('modifier')!r} created={get('created')} "
                f"params_applied={len(get('parameters_applied') or [])} "
                f"evaluated_vertices={evaluated.get('vertices')}")
