# --------------------------------------------------------------------------- #
# graph builder: unique names, layout labels, nodes before links, bounded batches
# --------------------------------------------------------------------------- #
class GraphBuilder:
    """Collects one phase worth of graph edits and reports them as bounded batches."""

    def __init__(
        self,
        group: str,
        existing_names: Iterable[str],
        sockets: Sockets,
        join_node: str = N_JOIN,
    ) -> None:
        self.group = group
        self.sockets = sockets
        self.join_node = join_node
        self._used: set[str] = set(existing_names)
        self._creates: list[dict[str, Any]] = []
        self._defaults: list[dict[str, Any]] = []
        self._links: list[dict[str, Any]] = []
        self._cursor: dict[int, float] = {}
        self.created: list[str] = []

    # -- naming / layout ---------------------------------------------------- #
    def _unique(self, name: str) -> str:
        if name not in self._used:
            self._used.add(name)
            return name
        index = 1
        while True:
            candidate = f"{name}.{index:03d}"
            if candidate not in self._used:
                self._used.add(candidate)
                return candidate
            index += 1

    def reuse(self, name: str) -> str:
        """Reference an existing node; refuse when it is not in the group."""
        if name not in self._used:
            raise RecipeError(f"node {name!r} does not exist in group {self.group!r}")
        return name

    # -- operations --------------------------------------------------------- #
    def add_node(
        self,
        node_type: str,
        name: str,
        column: int,
        *,
        label: str | None = None,
        settings: dict[str, Any] | None = None,
    ) -> str:
        unique = self._unique(name)
        location = [column * COLUMN_GAP, self._cursor.get(column, 0.0)]
        self._cursor[column] = location[1] - ROW_GAP
        operation: dict[str, Any] = {
            "op": "create_node",
            "node_type": node_type,
            "name": unique,
            "location": location,
        }
        if label:
            operation["label"] = label
        if settings:
            operation["settings"] = settings
        self._creates.append(operation)
        self.created.append(unique)
        return unique

    def set_default(self, node: str, socket: str, value: Any) -> None:
        # NOTE: set_socket_default/link_sockets batch ops take exactly the command
        # arguments; extra keys (e.g. a "label") would fail the whole transaction.
        self._defaults.append({
            "op": "set_socket_default",
            "node": node,
            "socket": socket,
            "value": value,
            "in_out": "INPUT",
        })

    def link(self, from_node: str, from_socket: str, to_node: str, to_socket: str) -> None:
        self._links.append({
            "op": "link_sockets",
            "from_node": from_node,
            "from_socket": from_socket,
            "to_node": to_node,
            "to_socket": to_socket,
            "replace": True,
        })

    def operations(self) -> list[dict[str, Any]]:
        """Creates first, then defaults, then links."""
        return self._creates + self._defaults + self._links

    def chunks(self) -> list[list[dict[str, Any]]]:
        operations = self.operations()
        if not operations:
            raise RecipeError("internal: the phase produced no graph operations")
        return [operations[i:i + BATCH_LIMIT] for i in range(0, len(operations), BATCH_LIMIT)]

    # -- convenience -------------------------------------------------------- #
    def math(
        self,
        name: str,
        operation: str,
        *,
        column: int = COL_PARAM,
        label: str | None = None,
        a: Source | None = None,
        a_default: float | None = None,
        b: Source | None = None,
        b_default: float | None = None,
    ) -> str:
        node = self.add_node(
            NT_MATH, name, column,
            label=label or f"{operation.lower()} ({name})",
            settings={"operation": operation},
        )
        if a is not None:
            self.link(a[0], a[1], node, self.sockets.math_a)
        elif a_default is not None:
            self.set_default(node, self.sockets.math_a, a_default)
        if b is not None:
            self.link(b[0], b[1], node, self.sockets.math_b)
        elif b_default is not None:
            self.set_default(node, self.sockets.math_b, b_default)
        return node

    def combine(
        self,
        name: str,
        *,
        column: int = COL_VECTOR,
        label: str | None = None,
        x: Source | float | None = None,
        y: Source | float | None = None,
        z: Source | float | None = None,
    ) -> str:
        node = self.add_node(NT_COMBINE, name, column, label=label or f"vector ({name})")
        for socket, value in (
            (self.sockets.xyz_x, x), (self.sockets.xyz_y, y), (self.sockets.xyz_z, z)
        ):
            if value is None:
                continue
            if isinstance(value, tuple):
                self.link(value[0], value[1], node, socket)
            else:
                self.set_default(node, socket, float(value))
        return node

    def transform(
        self,
        name: str,
        *,
        geometry: Source,
        column: int = COL_PART,
        label: str | None = None,
        translation: Source | None = None,
        scale: Source | None = None,
        rotation: Source | None = None,
    ) -> str:
        node = self.add_node(NT_TRANSFORM, name, column, label=label or f"place {name}")
        for socket, value in (
            (self.sockets.xform_translation, translation),
            (self.sockets.xform_scale, scale),
            (self.sockets.xform_rotation, rotation),
        ):
            if value is not None:
                self.link(value[0], value[1], node, socket)
        self.link(geometry[0], geometry[1], node, self.sockets.xform_geometry_in)
        return node

    def join(self, transform_node: str) -> None:
        """Append one part to the join node's multi-input Geometry socket."""
        self.link(
            transform_node, self.sockets.xform_geometry_out,
            self.join_node, self.sockets.join_geometry_in,
        )


async def apply_batches(ctx: "Ctx", builder: GraphBuilder, phase: str) -> int:
    """Send the collected edits as <= BATCH_LIMIT transactional batches."""
    chunks = builder.chunks()
    log(f"[batch] phase {phase!r}: {len(builder.operations())} operations "
        f"({len(builder.created)} node creations) in {len(chunks)} transactional batch(es)")
    completed = 0
    for position, chunk in enumerate(chunks, start=1):
        if len(chunk) > BATCH_LIMIT:
            raise RecipeError(f"internal: batch of {len(chunk)} operations exceeds {BATCH_LIMIT}")
        payload = await ctx.client.call(
            "blender_batch_graph_edit",
            {"group": ctx.group_name, "operations": chunk, "transactional": True},
        )
        if payload.get("rolled_back") or payload.get("failed_count"):
            raise RecipeError(
                f"batch {position}/{len(chunks)} of phase {phase!r} did not commit: "
                f"rolled_back={payload.get('rolled_back')} failures={payload.get('failures')}"
            )
        completed += int(payload.get("completed_count") or 0)
    return completed


