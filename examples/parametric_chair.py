#!/usr/bin/env python
"""Parametric wooden chair: a bounded, reusable MCP-client recipe.

What this is
------------
A single-file client recipe that drives the Blender MCP server
(``<MCP>/server.py``, stdio) through the **official** MCP SDK
(``mcp.ClientSession`` + ``mcp.client.stdio.stdio_client``) and builds one
parametric wooden chair out of Geometry Nodes.

Every model change goes through a *typed MCP tool* (``blender_*``); this file
never imports ``bpy``, never talks to the raw JSON bridge, never executes
arbitrary code in Blender and never launches or kills Blender. Reading the scene
uses the read-only tools, writing uses the mutating typed tools only. Nothing is
deleted or replaced automatically: when a node group or object with the target
name already exists, the phase stops and says so.

Architecture (one object, one carrier mesh, one node group)
-----------------------------------------------------------
* Object ``Parametric_Chair<suffix>`` at the world origin, real metres.
* Its base mesh is a **single origin vertex** (no edges, no faces). A carrier
  mesh cannot be truly empty through the typed tool - ``blender_create_mesh_object``
  rejects an empty vertex list - so the carrier is the smallest legal mesh and
  contributes no geometry: everything you see is generated by the node group, and
  only what is linked into Group Output is evaluated.
* Node group ``GN_Parametric_Chair<suffix>`` holds the whole chair. Parts are
  ``GeometryNodeMeshCube`` -> ``GeometryNodeTransform`` (scale + translation, and
  a rotation for the tilted back) -> one ``GeometryNodeJoinGeometry`` whose
  multi-input ``Geometry`` socket receives every part -> ``Group Output``.
* Every dimension is driven by group inputs (English names, real metres) and
  every derived value (half thickness, leg centre, tilt sine/cosine, rail
  spacing) is a Math/CombineXYZ node, so nothing is baked into the mesh.

Coordinate convention
---------------------
+Z up, the back of the chair towards **+Y** (the sitter faces -Y), +X to the
right. ``Back Tilt`` is in radians and is applied as a **negative X rotation**,
which leans the back posts towards +Y.

Phases (one phase per invocation, in this order)
------------------------------------------------
``inspect`` read-only discovery: health, scene, node-type sockets, existing chair
           assets and the current graph summary.
``seat``   create the node group (typed interface), the carrier mesh object and
           the modifier, and build the seat board (already linked to Group Output).
``legs``   append four legs into the join node.
``back``   append the two tilted back posts and three rails.
``finish`` write the ``recipe`` / ``version`` / ``description`` custom properties.
``verify`` drive ``Seat Width`` and ``Seat Height`` through the modifier inputs,
           prove the evaluated bounds change by the expected amount, restore the
           original values, then render a 960x720 preview PNG.
``save``   ``blender_save_blend`` to ``Project/chairs/parametric_chair.blend``
           (overwrite=false, no .blend1 backups, nothing else written).

Usage (from ``<MCP>``)
----------------------
    .venv\\Scripts\\python.exe examples\\parametric_chair.py --phase inspect
    .venv\\Scripts\\python.exe examples\\parametric_chair.py --phase seat
    .venv\\Scripts\\python.exe examples\\parametric_chair.py --phase legs
    .venv\\Scripts\\python.exe examples\\parametric_chair.py --phase back
    .venv\\Scripts\\python.exe examples\\parametric_chair.py --phase finish
    .venv\\Scripts\\python.exe examples\\parametric_chair.py --phase verify
    .venv\\Scripts\\python.exe examples\\parametric_chair.py --phase save

Blender must already be running with the bridge listening (default port 9876,
started from ``blender/bootstrap.py`` or ``launch_blender.ps1``); every invocation
calls ``blender_health`` first and fails with an actionable message when the
bridge is not there.

Notes and known limits
----------------------
* The recipe sets ``BLENDER_MCP_PORT`` for the server process (``--port``,
  default 9876, itself defaulting to the ambient ``BLENDER_MCP_PORT``).
* No typed tool creates a collection. If ``Parametric Chairs`` does not exist the
  object is linked to the scene collection and the phase reports that as a
  warning instead of pretending the collection was used.
* ``legs`` and ``back`` *append* links to the join node's multi-input socket.
  After each append phase the recipe re-inspects the group and asserts the real
  link count, so "the link replaced instead of appended" cannot pass silently.
* ``back`` reuses the offset nodes built by ``legs`` (one source of truth for the
  part offsets); run the phases in order or ``back`` refuses with a clear message.
* The preview is the only local file the verify phase may touch; an existing
  preview is replaced only after a first, deliberately non-destructive attempt
  failed, and that replacement is reported as a warning.
"""

