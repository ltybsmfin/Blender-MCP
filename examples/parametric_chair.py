def _permission_hint(exc: BaseException) -> str | None:
    """Recognise a denied pipe creation, including inside an ExceptionGroup."""
    seen: set[int] = set()
    stack: list[BaseException] = [exc]
    while stack:
        current = stack.pop()
        if id(current) in seen:
            continue
        seen.add(id(current))
        if isinstance(current, PermissionError) or "WinError 5" in str(current):
            return (
                "the MCP server process could not be started: this environment denied creating the "
                "stdio pipes (PermissionError / WinError 5). The official stdio_client is used on "
                "purpose; on a normally-permissioned account it works, and tests/stdio_pipe_transport.py "
                "documents the pipe workaround the test suite uses in restricted environments."
            )
        for nested in getattr(current, "exceptions", None) or []:
            stack.append(nested)
        cause = current.__cause__ or current.__context__
        if cause is not None:
            stack.append(cause)
    return None


async def run(args: argparse.Namespace) -> None:
    args.suffix = validate_suffix(args.suffix)
    python = Path(args.python)
    if not python.is_file():
        raise RecipeError(
            f"interpreter {python} does not exist; pass --python or create the project .venv"
        )
    if not SERVER_SCRIPT.is_file():
        raise RecipeError(f"MCP server entry point {SERVER_SCRIPT} does not exist")

    env = {
        "BLENDER_MCP_PORT": str(int(args.port)),
        "PYTHONUNBUFFERED": "1",
        "PYTHONUTF8": "1",
    }
    parameters = StdioServerParameters(
        command=str(python), args=[str(SERVER_SCRIPT)], env=env, cwd=str(MCP_DIR)
    )
    log(f"[start] python={python}")
    log(f"[start] server={SERVER_SCRIPT} env=BLENDER_MCP_PORT={env['BLENDER_MCP_PORT']}")

    try:
        async with stdio_client(parameters) as (read_stream, write_stream):
            async with ClientSession(read_stream, write_stream) as session:
                await session.initialize()
                client = ToolClient(session, args.timeout)
                ctx = Ctx(client=client, discovery=Discovery(client), args=args)
                await prelude(ctx)
                await PHASE_HANDLERS[args.phase](ctx)
                log(f"[done] phase {args.phase!r} finished; {client.calls} MCP tool call(s) made")
                if ctx.warnings:
                    log(f"[done] {len(ctx.warnings)} warning(s):")
                    for warning in ctx.warnings:
                        log(f"  - {warning}")
    except (PermissionError, OSError) as exc:
        hint = _permission_hint(exc)
        if hint:
            raise RecipeError(hint) from exc
        raise


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        asyncio.run(run(args))
    except RecipeError as exc:
        print(f"[error] {exc}", file=sys.stderr, flush=True)
        return 2
    except KeyboardInterrupt:  # pragma: no cover - interactive interruption
        print("[error] interrupted", file=sys.stderr, flush=True)
        return 130
    except BaseException as exc:  # noqa: BLE001 - report once, never guess
        hint = _permission_hint(exc)
        if hint:
            print(f"[error] {hint}", file=sys.stderr, flush=True)
            return 2
        raise
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
