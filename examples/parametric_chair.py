class RecipeError(RuntimeError):
    """A bounded failure the recipe reports as a non-zero exit."""


def log(message: str) -> None:
    print(message, flush=True)


def validate_suffix(suffix: str) -> str:
    """Keep generated datablock names predictable and readable."""
    if suffix and not re.fullmatch(r"[A-Za-z0-9_.\-]{1,32}", suffix):
        raise RecipeError(
            f"--suffix {suffix!r} is not usable: 1..32 characters from A-Za-z0-9_.- only"
        )
    return suffix


