async def phase_inspect(ctx: Ctx) -> None:
    summary = await ctx.client.call("blender_scene_summary", {"include_objects": True})
    log(f"[scene] units={summary.get('unit_system')} blend={summary.get('blend_filepath')!r}")
    log(f"[scene] collections={summary.get('collections')}")
    for group in summary.get("node_groups") or []:
        log(f"[scene] node_group {group.get('name')!r} type={group.get('type')} "
            f"nodes={group.get('nodes')} users={group.get('users')}")

    objects = await ctx.client.call("blender_list_objects", {"name_contains": OBJECT_STEM, "limit": 50})
    log(f"[scene] objects matching {OBJECT_STEM!r}: "
        f"{[(row.get('name'), row.get('type')) for row in objects.get('objects') or []]}")
    collection_ready = COLLECTION_NAME in (summary.get("collections") or [])
    log(f"[scene] collection {COLLECTION_NAME!r} present: {collection_ready}")

    log("[discover] node-type sockets reported by this Blender build:")
    for node_type in NODE_TYPES:
        payload = await ctx.discovery.describe(node_type)
        log(f"  {node_type}: label={payload.get('bl_label')!r}")
        for direction in ("inputs", "outputs"):
            sockets = payload.get(direction) or []
            log(f"    {direction[:3]:<3}: " + ", ".join(
                f"{s.get('name')}({s.get('identifier')}:{s.get('type')})" for s in sockets))
    if ctx.discovery.duplicate_input_names(NT_MATH, 0):
        log(f"[discover] {NT_MATH} exposes duplicate display names for its operands; the recipe "
            f"addresses them by the identifiers discovered above, never by display name")

    group_names = {g.get("name") for g in summary.get("node_groups") or []}
    group: GroupView | None = None
    if ctx.group_name in group_names:
        group = await ctx.group_view()
        sockets = await ctx.sockets(group)
        join_links = group.join_input_links(N_JOIN, sockets.join_geometry_in)
        log(f"[chair] {ctx.group_name!r}: nodes={len(group.nodes)} links={len(group.links)} "
            f"iface_in={len(group.iface_in)} iface_out={len(group.iface_out)}")
        log("[chair] interface inputs: "
            + ", ".join(f"{name}({identifier})" for name, identifier in group.iface_in.items()))
        log(f"[chair] join multi-input links: {len(join_links)} "
            f"(complete chair = {EXPECTED_JOIN_LINKS['back']})")
    else:
        log(f"[chair] {ctx.group_name!r} does not exist yet")

    log(f"[plan] next phase to run: {_next_phase(ctx, group)}")


def _next_phase(ctx: Ctx, group: GroupView | None) -> str:
    if group is None:
        return "seat"
    for phase in ("legs", "back"):
        if any(name not in group.nodes for name in PHASE_PART_NODES[phase]):
            return phase
    return "finish"


async def phase_seat(ctx: Ctx) -> None:
    summary = await ctx.client.call("blender_scene_summary", {"include_objects": False})
    group_names = {g.get("name") for g in summary.get("node_groups") or []}
    if ctx.group_name in group_names:
        raise RecipeError(
            f"node group {ctx.group_name!r} already exists: refusing to replace it. Pass a distinct "
            f"--suffix to build another chair, or remove it yourself in Blender (this recipe never "
            f"deletes or replaces existing assets)."
        )
    objects = await ctx.client.call("blender_list_objects", {"name_contains": ctx.object_name})
    if any(row.get("name") == ctx.object_name for row in objects.get("objects") or []):
        raise RecipeError(
            f"object {ctx.object_name!r} already exists: refusing to replace it. Pass a distinct "
            f"--suffix or remove it yourself in Blender."
        )

    interface = [
        {
            "name": param.name,
            "socket_type": "NodeSocketFloat",
            "in_out": "INPUT",
            "default_value": param.default,
            "min_value": param.minimum,
            "max_value": param.maximum,
            "description": param.description,
            **({"subtype": param.subtype} if param.subtype else {}),
        }
        for param in PARAMS
    ] + [
        {"name": "Geometry", "socket_type": "NodeSocketGeometry", "in_out": "OUTPUT",
         "description": "The finished chair, ready for the modifier output"},
    ]
    await ctx.client.call(
        "blender_create_node_group",
        {"name": ctx.group_name, "interface": interface, "if_exists": "error"},
    )

    # Group Input/Output and the interface are used with the identifiers Blender
    # really created, never with guessed names.
    group = await ctx.group_view()
    missing = [param.name for param in PARAMS if param.name not in group.iface_in]
    unexpected = [name for name in group.iface_in if name not in PARAM_BY_NAME]
    if missing or unexpected or len(group.iface_in) != len(PARAMS) or "Geometry" not in group.iface_out:
        raise RecipeError(
            f"the created group does not expose the expected interface (missing={missing} "
            f"unexpected={unexpected} inputs={len(group.iface_in)}/{len(PARAMS)} "
            f"geometry_out={'Geometry' in group.iface_out}); group {ctx.group_name!r} was created and is "
            f"left untouched for inspection"
        )
    for param in PARAMS:
        group.group_input_source(param.name)
    group.group_output_target("Geometry")
    log("[discover] " + ctx.group_name + " interface => "
        + ", ".join(f"{name}({identifier})" for name, identifier in group.iface_in.items()))

    sockets = await ctx.sockets(group)
    builder = GraphBuilder(ctx.group_name, group.nodes, sockets)
    builder.join_node = builder.add_node(NT_JOIN, N_JOIN, COL_JOIN, label="join every chair part")
    unit_cube = builder.add_node(NT_CUBE, N_UNIT_CUBE, COL_PART, label="shared unit cube (1 m)")
    builder.set_default(unit_cube, sockets.cube_size, [1.0, 1.0, 1.0])

    seat_scale = builder.combine(
        "Seat_Size_XYZ", label="seat board size",
        x=sockets.source("Seat Width"), y=sockets.source("Seat Depth"),
        z=sockets.source("Seat Thickness"),
    )
    half_thickness = builder.math(
        "Seat_Half_Thickness", OP_DIVIDE, label="SeatThickness / 2",
        a=sockets.source("Seat Thickness"), b_default=2.0,
    )
    seat_center_z = builder.math(
        "Seat_Center_Z", OP_SUBTRACT, label="SeatHeight - SeatThickness/2",
        a=sockets.source("Seat Height"), b=(half_thickness, sockets.math_out),
    )
    seat_center = builder.combine("Seat_Center_XYZ", label="seat centre",
                                  z=(seat_center_z, sockets.math_out))
    seat_transform = builder.transform(
        "Seat_Transform", label="seat board", geometry=(unit_cube, sockets.cube_mesh),
        translation=(seat_center, sockets.xyz_vector), scale=(seat_scale, sockets.xyz_vector),
    )
    builder.join(seat_transform)
    builder.link(builder.join_node, sockets.join_geometry_out, group.node_out,
                 sockets.group_out_geometry)
    await apply_batches(ctx, builder, "seat")

    collection_ready = COLLECTION_NAME in (summary.get("collections") or [])
    if not collection_ready:
        ctx.warn(
            f"collection {COLLECTION_NAME!r} does not exist and no typed tool creates collections; the "
            f"chair is linked to the scene collection instead - create the collection in Blender and "
            f"re-run --phase seat with a fresh --suffix if you need it"
        )
    await ctx.client.call(
        "blender_create_mesh_object",
        {
            "name": ctx.object_name,
            "vertices": [[0.0, 0.0, 0.0]],
            "faces": [],
            "collection": COLLECTION_NAME if collection_ready else None,
            "location": [0.0, 0.0, 0.0],
        },
    )
    log("[note] the carrier mesh has exactly one vertex and no faces on purpose: the visible chair is "
        "generated by the node group, and only its Group Output is evaluated")

    parameters = {param.name: param.default for param in PARAMS}
    attach = await ctx.client.call(
        "blender_attach_geometry_nodes_modifier",
        {"object": ctx.object_name, "group": ctx.group_name, "modifier_name": MODIFIER_NAME,
         "parameters": parameters},
    )
    failed = attach.get("parameters_failed") or []
    if failed:
        raise RecipeError(
            f"the modifier was attached but these parameters were refused: {failed}. Exposed inputs: "
            f"{sorted((attach.get('parameters') or {}).keys())}"
        )
    info = await ctx.object_info()
    bounds = evaluated_bounds(info)
    log(f"[seat] evaluated vertices={((info.get('mesh') or {}).get('evaluated') or {}).get('vertices')} "
        f"bounds min={bounds['min']} max={bounds['max']}")
    await ctx.assert_join_link_count("seat")


def _guard_append_phase(group: GroupView, phase: str) -> bool:
    """True when the phase is already built; raise when it is half-built."""
    parts = PHASE_PART_NODES[phase]
    present = [name for name in parts if name in group.nodes]
    if len(present) == len(parts):
        log(f"[skip] phase {phase!r} is already built in {group.name!r} ({present}); nothing appended")
        return True
    if present:
        raise RecipeError(
            f"phase {phase!r} looks half-built in group {group.name!r}: {present} exist but "
            f"{[n for n in parts if n not in present]} do not. Nothing was changed; inspect the group "
            f"before deciding, because re-running would duplicate geometry."
        )
    return False


async def phase_legs(ctx: Ctx) -> None:
    group = await ctx.require_group()
    await ctx.require_object()
    sockets = await ctx.sockets(group)
    group.require_nodes([N_UNIT_CUBE, N_JOIN], "legs")
    if _guard_append_phase(group, "legs"):
        await ctx.assert_join_link_count("legs", exact=False)
        return

    builder = GraphBuilder(ctx.group_name, group.nodes, sockets)
    unit_cube = builder.reuse(N_UNIT_CUBE)

    leg_height = builder.math(
        "Leg_Height", OP_SUBTRACT, label="SeatHeight - SeatThickness",
        a=sockets.source("Seat Height"), b=sockets.source("Seat Thickness"),
    )
    leg_center_z = builder.math(
        "Leg_Center_Z", OP_DIVIDE, label="leg height / 2",
        a=(leg_height, sockets.math_out), b_default=2.0,
    )
    leg_size = builder.combine(
        "Leg_Size_XYZ", label="leg cross-section x height",
        x=sockets.source("Leg Size"), y=sockets.source("Leg Size"), z=(leg_height, sockets.math_out),
    )
    x_span = builder.math(
        "Leg_X_Span", OP_SUBTRACT, label="SeatWidth - LegSize",
        a=sockets.source("Seat Width"), b=sockets.source("Leg Size"),
    )
    x_half = builder.math(
        N_LEG_X_HALF, OP_DIVIDE, label="half leg x offset",
        a=(x_span, sockets.math_out), b_default=2.0,
    )
    y_span = builder.math(
        "Leg_Y_Span", OP_SUBTRACT, label="SeatDepth - LegSize",
        a=sockets.source("Seat Depth"), b=sockets.source("Leg Size"),
    )
    y_half = builder.math(
        N_LEG_Y_HALF, OP_DIVIDE, label="half leg y offset",
        a=(y_span, sockets.math_out), b_default=2.0,
    )
    x_neg = builder.math(
        N_LEG_X_NEG, OP_MULTIPLY, label="-x leg offset",
        a=(x_half, sockets.math_out), b_default=-1.0,
    )
    y_neg = builder.math(
        "Leg_Y_Neg", OP_MULTIPLY, label="-y leg offset",
        a=(y_half, sockets.math_out), b_default=-1.0,
    )
    x_sources: dict[int, Source] = {+1: (x_half, sockets.math_out), -1: (x_neg, sockets.math_out)}
    y_sources: dict[int, Source] = {+1: (y_half, sockets.math_out), -1: (y_neg, sockets.math_out)}
    for key, x_sign, y_sign in LEG_PARTS:
        center = builder.combine(
            f"Leg_{key}_Center_XYZ", label=f"{key.lower()} leg centre",
            x=x_sources[x_sign], y=y_sources[y_sign], z=(leg_center_z, sockets.math_out),
        )
        transform = builder.transform(
            f"Leg_{key}_Transform", label=f"{key.lower()} leg", geometry=(unit_cube, sockets.cube_mesh),
            translation=(center, sockets.xyz_vector), scale=(leg_size, sockets.xyz_vector),
        )
        builder.join(transform)

    await apply_batches(ctx, builder, "legs")
    await ctx.assert_join_link_count("legs")
    info = await ctx.object_info()
    bounds = evaluated_bounds(info)
    log(f"[legs] bounds min={bounds['min']} max={bounds['max']} "
        f"vertices={((info.get('mesh') or {}).get('evaluated') or {}).get('vertices')}")


async def phase_back(ctx: Ctx) -> None:
    group = await ctx.require_group()
    await ctx.require_object()
    sockets = await ctx.sockets(group)
    group.require_nodes([N_UNIT_CUBE, N_JOIN, N_LEG_X_HALF, N_LEG_X_NEG, N_LEG_Y_HALF], "back")
    if _guard_append_phase(group, "back"):
        await ctx.assert_join_link_count("back", exact=False)
        return

    builder = GraphBuilder(ctx.group_name, group.nodes, sockets)
    unit_cube = builder.reuse(N_UNIT_CUBE)
    x_half = builder.reuse(N_LEG_X_HALF)
    x_neg = builder.reuse(N_LEG_X_NEG)
    y_half = builder.reuse(N_LEG_Y_HALF)

    # Tilt arithmetic: SINE/COSINE are radians and the post rotation is
    # -Back Tilt about X, which leans the posts towards +Y (the back of the chair).
    sin_tilt = builder.math("Back_Sin_Tilt", OP_SINE, label="sin(BackTilt)",
                            a=sockets.source("Back Tilt"))
    cos_tilt = builder.math("Back_Cos_Tilt", OP_COSINE, label="cos(BackTilt)",
                            a=sockets.source("Back Tilt"))
    neg_tilt = builder.math("Back_Tilt_Neg", OP_MULTIPLY, label="-BackTilt (X rotation)",
                            a=sockets.source("Back Tilt"), b_default=-1.0)
    rotation = builder.combine("Back_Rotation_XYZ", label="back rotation (-tilt, 0, 0)",
                               x=(neg_tilt, sockets.math_out))
    half_length = builder.math("Back_Half_Length", OP_DIVIDE, label="BackHeight / 2",
                               a=sockets.source("Back Height"), b_default=2.0)
    axis_y = builder.math("Back_Axis_Y", OP_MULTIPLY, label="(BackHeight/2) * sin(tilt)",
                          a=(half_length, sockets.math_out), b=(sin_tilt, sockets.math_out))
    axis_z = builder.math("Back_Axis_Z", OP_MULTIPLY, label="(BackHeight/2) * cos(tilt)",
                          a=(half_length, sockets.math_out), b=(cos_tilt, sockets.math_out))
    post_center_y = builder.math("Back_Center_Y", OP_ADD, label="rear leg y + axis y",
                                 a=(y_half, sockets.math_out), b=(axis_y, sockets.math_out))
    post_center_z = builder.math("Back_Center_Z", OP_ADD, label="SeatHeight + axis z",
                                 a=sockets.source("Seat Height"), b=(axis_z, sockets.math_out))
    post_size = builder.combine(
        "Back_Post_Size_XYZ", label="post cross-section x BackHeight",
        x=sockets.source("Leg Size"), y=sockets.source("Leg Size"), z=sockets.source("Back Height"),
    )
    rail_length = builder.math("Back_Rail_Length", OP_SUBTRACT, label="SeatWidth - LegSize (rail span)",
                               a=sockets.source("Seat Width"), b=sockets.source("Leg Size"))
    rail_size = builder.combine(
        "Back_Rail_Size_XYZ", label="rail cross-section",
        x=(rail_length, sockets.math_out), y=sockets.source("Leg Size"),
        z=sockets.source("Leg Size"),
    )
    rail_span = builder.math("Back_Rail_Span", OP_SUBTRACT, label="BackHeight - RailHeight",
                             a=sockets.source("Back Height"), b=sockets.source("Rail Height"))
    rail_step = builder.math("Back_Rail_Step", OP_DIVIDE, label="(BackHeight - RailHeight) / 3",
                             a=(rail_span, sockets.math_out), b_default=3.0)
    distance_1 = builder.math("Back_Rail_Distance_1", OP_ADD, label="RailHeight + step",
                              a=sockets.source("Rail Height"), b=(rail_step, sockets.math_out))
    step_2 = builder.math("Back_Rail_Step_2", OP_MULTIPLY, label="2 * step",
                          a=(rail_step, sockets.math_out), b_default=2.0)
    distance_2 = builder.math("Back_Rail_Distance_2", OP_ADD, label="RailHeight + 2 * step",
                              a=sockets.source("Rail Height"), b=(step_2, sockets.math_out))
    distance_sources: tuple[Source, ...] = (
        sockets.source("Rail Height"),
        (distance_1, sockets.math_out),
        (distance_2, sockets.math_out),
    )

    for key, x_source in (("Right", (x_half, sockets.math_out)), ("Left", (x_neg, sockets.math_out))):
        center = builder.combine(
            f"Back_Post_{key}_Center_XYZ", label=f"{key.lower()} post centre",
            x=x_source, y=(post_center_y, sockets.math_out), z=(post_center_z, sockets.math_out),
        )
        transform = builder.transform(
            f"Back_Post_{key}_Transform", label=f"{key.lower()} back post",
            geometry=(unit_cube, sockets.cube_mesh), translation=(center, sockets.xyz_vector),
            scale=(post_size, sockets.xyz_vector), rotation=(rotation, sockets.xyz_vector),
        )
        builder.join(transform)

    for key, index in RAIL_PARTS:
        distance = distance_sources[index]
        rail_y_mul = builder.math(f"Back_Rail_{key}_Y_Mul", OP_MULTIPLY,
                                  label=f"{key.lower()} rail y offset",
                                  a=distance, b=(sin_tilt, sockets.math_out))
        rail_y = builder.math(f"Back_Rail_{key}_Y", OP_ADD, label=f"{key.lower()} rail centre y",
                              a=(y_half, sockets.math_out), b=(rail_y_mul, sockets.math_out))
        rail_z_mul = builder.math(f"Back_Rail_{key}_Z_Mul", OP_MULTIPLY,
                                  label=f"{key.lower()} rail z offset",
                                  a=distance, b=(cos_tilt, sockets.math_out))
        rail_z = builder.math(f"Back_Rail_{key}_Z", OP_ADD, label=f"{key.lower()} rail centre z",
                              a=sockets.source("Seat Height"), b=(rail_z_mul, sockets.math_out))
        center = builder.combine(f"Back_Rail_{key}_Center_XYZ", label=f"{key.lower()} rail centre",
                                 y=(rail_y, sockets.math_out), z=(rail_z, sockets.math_out))
        transform = builder.transform(
            f"Back_Rail_{key}_Transform", label=f"{key.lower()} back rail",
            geometry=(unit_cube, sockets.cube_mesh), translation=(center, sockets.xyz_vector),
            scale=(rail_size, sockets.xyz_vector), rotation=(rotation, sockets.xyz_vector),
        )
        builder.join(transform)

    await apply_batches(ctx, builder, "back")
    await ctx.assert_join_link_count("back")
    info = await ctx.object_info()
    bounds = evaluated_bounds(info)
    log(f"[back] bounds min={bounds['min']} max={bounds['max']} "
        f"vertices={((info.get('mesh') or {}).get('evaluated') or {}).get('vertices')}")


async def phase_finish(ctx: Ctx) -> None:
    await ctx.require_object()
    group = await ctx.require_group()
    sockets = await ctx.sockets(group)
    links = group.join_input_links(N_JOIN, sockets.join_geometry_in)
    if len(links) != EXPECTED_JOIN_LINKS["back"]:
        ctx.warn(
            f"the graph holds {len(links)} part link(s) on {N_JOIN!r}, not "
            f"{EXPECTED_JOIN_LINKS['back']}: metadata is written anyway, but run the missing phases "
            f"before saving"
        )
    description = (
        "Parametric wooden chair built by examples/parametric_chair.py through the Blender MCP typed "
        "tools. Geometry Nodes only: every dimension is an exposed group input in metres, the back is "
        "+Y and Back Tilt is in radians. Parts: seat board, four legs, two tilted back posts and three "
        "rails. Rebuild with --phase inspect|seat|legs|back|finish|verify|save."
    )
    for key, value in (("recipe", RECIPE_NAME), ("version", RECIPE_VERSION),
                       ("description", description)):
        await ctx.client.call(
            "blender_set_custom_property",
            {"owner_kind": "object", "owner_name": ctx.object_name, "key": key, "value": value},
        )
    info = await ctx.object_info()
    log(f"[finish] custom properties: "
        + _compact({k: v for k, v in (info.get("custom_properties") or {}).items()}, 400))
    log("[finish] modifier parameters: " + _compact(
        {entry.get("name"): entry.get("value")
         for entry in modifier_parameters(info, ctx.group_name).values()}, 400))


async def phase_verify(ctx: Ctx) -> None:
    info = await ctx.require_object()
    group = await ctx.require_group()
    sockets = await ctx.sockets(group)
    links = group.join_input_links(N_JOIN, sockets.join_geometry_in)
    if len(links) != EXPECTED_JOIN_LINKS["back"]:
        raise RecipeError(
            f"the chair is incomplete: {N_JOIN!r} holds {len(links)} part link(s), expected "
            f"{EXPECTED_JOIN_LINKS['back']}. Run the missing phases (legs/back) before verifying."
        )

    identifiers = {param.name: group.interface_identifier(param.name) for param in PARAMS}
    current = modifier_parameters(info, ctx.group_name)
    values: dict[str, float] = {}
    for param in PARAMS:
        entry = current.get(identifiers[param.name]) or {}
        value = entry.get("value")
        if not isinstance(value, (int, float)) or isinstance(value, bool):
            raise RecipeError(
                f"cannot read the current value of {param.name!r} from the modifier: {entry!r}"
            )
        values[param.name] = float(value)

    bounds = evaluated_bounds(info)
    baseline = {
        "width": float(bounds["max"][0] - bounds["min"][0]),
        "max_z": float(bounds["max"][2]),
        "min_z": float(bounds["min"][2]),
        "max_y": float(bounds["max"][1]),
        "min_y": float(bounds["min"][1]),
        "vertices": ((info.get("mesh") or {}).get("evaluated") or {}).get("vertices"),
    }
    log(f"[verify] baseline: Seat Width={values['Seat Width']} Seat Height={values['Seat Height']} "
        f"width={baseline['width']:.4f} z=[{baseline['min_z']:.4f}, {baseline['max_z']:.4f}] "
        f"y=[{baseline['min_y']:.4f}, {baseline['max_y']:.4f}] vertices={baseline['vertices']}")

    checks: list[tuple[str, bool, str]] = []
    steps = (
        ("Seat Width", 0.60, "width", +0.12),
        ("Seat Height", 0.52, "max_z", +0.07),
    )
    try:
        for name, target, metric, delta in steps:
            stepped = await ctx.client.call(
                "blender_set_modifier_input",
                {"object": ctx.object_name, "input": identifiers[name], "value": target,
                 "modifier": MODIFIER_NAME, "include_evaluated": True},
            )
            step_bounds = (stepped.get("evaluated") or {}).get("bounds") or {}
            if not step_bounds:
                raise RecipeError(f"the modifier input {name!r} produced no evaluated bounds")
            observed = {
                "width": float(step_bounds["max"][0] - step_bounds["min"][0]),
                "max_z": float(step_bounds["max"][2]),
            }[metric]
            change = observed - baseline[metric]
            checks.append((
                f"{name} {values[name]:.3f} -> {target:.3f} moves {metric} by {delta:+.3f}",
                abs(change - delta) <= BOUNDS_TOLERANCE,
                f"{metric}={observed:.4f} delta={change:+.4f} tolerance={BOUNDS_TOLERANCE}",
            ))
            restored = await ctx.client.call(
                "blender_set_modifier_input",
                {"object": ctx.object_name, "input": identifiers[name], "value": values[name],
                 "modifier": MODIFIER_NAME, "include_evaluated": True},
            )
            restored_bounds = (restored.get("evaluated") or {}).get("bounds") or {}
            back = {
                "width": float(restored_bounds["max"][0] - restored_bounds["min"][0]),
                "max_z": float(restored_bounds["max"][2]),
            }[metric]
            checks.append((
                f"{name} restored to {values[name]:.3f}",
                abs(back - baseline[metric]) <= RESTORE_TOLERANCE,
                f"{metric}={back:.4f} baseline={baseline[metric]:.4f}",
            ))
    finally:
        # Never leave a verification parameter behind, even after a failed check.
        fresh = modifier_parameters(await ctx.object_info(), ctx.group_name)
        for param in PARAMS:
            entry = fresh.get(identifiers[param.name]) or {}
            if not isinstance(entry.get("value"), (int, float)):
                continue
            if abs(float(entry["value"]) - values[param.name]) > 1e-9:
                ctx.warn(f"{param.name!r} was still modified; restoring {values[param.name]}")
                await ctx.client.call(
                    "blender_set_modifier_input",
                    {"object": ctx.object_name, "input": identifiers[param.name],
                     "value": values[param.name], "modifier": MODIFIER_NAME,
                     "include_evaluated": False},
                )

    # Model agreement: the evaluated bounds must match the arithmetic the graph
    # implements, computed here from the same live parameter values.
    prediction = expected_bounds(values)
    for label, observed, expected in (
        ("width == Seat Width", baseline["width"], prediction["max_x"] - prediction["min_x"]),
        ("min_z == 0 (legs stand on the floor)", baseline["min_z"], prediction["min_z"]),
        ("max_z == SeatHeight + BackHeight*cos(tilt) + (LegSize/2)*sin(tilt)",
         baseline["max_z"], prediction["max_z"]),
        ("max_y == rear post top (tilt leans towards +Y)", baseline["max_y"], prediction["max_y"]),
        ("min_y == front leg face", baseline["min_y"], prediction["min_y"]),
    ):
        checks.append((
            label,
            abs(observed - expected) <= BOUNDS_TOLERANCE,
            f"observed={observed:.4f} predicted={expected:.4f}",
        ))

    for label, ok, detail in checks:
        log(f"[verify] {'OK  ' if ok else 'FAIL'} {label}: {detail}")
    failed = [label for label, ok, _ in checks if not ok]
    if failed:
        raise RecipeError(
            f"{len(failed)} verification check(s) failed: {failed}. The graph did not produce the "
            f"geometry this recipe predicts; inspect the group before trusting the model."
        )
    log(f"[verify] all {len(checks)} checks passed")

    await _capture_preview(ctx)


async def _capture_preview(ctx: Ctx) -> None:
    arguments: dict[str, Any] = {
        "object": ctx.object_name,
        "path": PREVIEW_RELATIVE_PATH,
        "mode": "render",
        "view": "isometric",
        "width": PREVIEW_WIDTH,
        "height": PREVIEW_HEIGHT,
        "timeout": PREVIEW_TOOL_TIMEOUT,
        "overwrite": False,
    }
    try:
        payload = await ctx.client.call("blender_capture_preview", arguments,
                                       timeout=PREVIEW_CALL_TIMEOUT, quiet=True)
    except RecipeError as exc:
        if "already exists" not in str(exc):
            raise
        ctx.warn(
            f"preview {PREVIEW_RELATIVE_PATH!r} already existed; it was replaced on a second, explicit "
            f"attempt after the first non-destructive attempt was refused"
        )
        arguments["overwrite"] = True
        payload = await ctx.client.call("blender_capture_preview", arguments,
                                       timeout=PREVIEW_CALL_TIMEOUT, quiet=True)
    log(f"[preview] {summarize('blender_capture_preview', payload)}")
    log("[preview] the PNG is returned as MCP image content on the tool result; this recipe prints the "
        "metadata only so the log stays readable")


async def phase_save(ctx: Ctx) -> None:
    info = await ctx.require_object()
    if (info.get("custom_properties") or {}).get("recipe") != RECIPE_NAME:
        ctx.warn(f"the object has no {RECIPE_NAME!r} custom property yet; run --phase finish first")
    try:
        payload = await ctx.client.call(
            "blender_save_blend",
            {"relative_path": SAVE_RELATIVE_PATH, "overwrite": bool(ctx.args.overwrite_save),
             "compress": False},
        )
    except RecipeError as exc:
        if "already exists" in str(exc) or "file_exists" in str(exc):
            raise RecipeError(
                f"{exc} - pass --overwrite-save to replace it deliberately (overwrite defaults to "
                f"false by design)"
            ) from exc
        raise
    log(f"[save] {payload.get('path')} ({payload.get('bytes')} bytes, "
        f"overwritten={payload.get('overwritten')})")
    log("[save] nothing else was written: no .blend1 backup, no preview, no thumbnail cache")


