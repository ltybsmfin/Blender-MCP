# live discovery: node-type sockets and the group view
# --------------------------------------------------------------------------- #
class Discovery:
    """Node-type socket identifiers, discovered once per invocation."""

    def __init__(self, client: ToolClient) -> None:
        self.client = client
        self._types: dict[str, dict[str, Any]] = {}

    async def describe_all(self) -> None:
        for node_type in NODE_TYPES:
            await self.describe(node_type)

    async def describe(self, node_type: str) -> dict[str, Any]:
        if node_type not in self._types:
            self._types[node_type] = await self.client.call(
                "blender_describe_node_type", {"node_type": node_type}
            )
        return self._types[node_type]

    def _sockets(self, node_type: str, direction: str) -> list[dict[str, Any]]:
        payload = self._types.get(node_type)
        if payload is None:
            raise RecipeError(
                f"internal: describe({node_type!r}) was not called before resolving a socket"
            )
        sockets = payload.get(direction) or []
        if not sockets:
            raise RecipeError(
                f"{node_type} reports no {direction.upper()} sockets in this Blender build; "
                f"the recipe cannot build the graph"
            )
        return sockets

    def input(self, node_type: str, name: str) -> str:
        return self._resolve(node_type, "inputs", name)

    def output(self, node_type: str, name: str) -> str:
        return self._resolve(node_type, "outputs", name)

    def input_by_index(self, node_type: str, index: int) -> dict[str, Any]:
        for socket in self._sockets(node_type, "inputs"):
            if int(socket.get("index", -1)) == index:
                return socket
        raise RecipeError(f"{node_type} has no input socket at index {index}")

    def duplicate_input_names(self, node_type: str, index: int) -> bool:
        """True when the socket at ``index`` shares its display name with another input."""
        sockets = self._sockets(node_type, "inputs")
        if index >= len(sockets):
            return False
        name = sockets[index].get("name")
        return sum(1 for socket in sockets if socket.get("name") == name) > 1

    def _resolve(self, node_type: str, direction: str, name: str) -> str:
        sockets = self._sockets(node_type, direction)
        for socket in sockets:
            if socket.get("name") == name or socket.get("identifier") == name:
                return str(socket["identifier"])
        available = ", ".join(f"{s.get('name')}({s.get('identifier')})" for s in sockets)
        raise RecipeError(
            f"{node_type} has no {direction[:-1]} socket named {name!r} in this Blender build; "
            f"available: {available}"
        )


@dataclass
class GroupView:
    """The parts of a live ``blender_inspect_node_group`` report the recipe uses."""

    name: str
    node_in: str
    node_out: str
    iface_in: dict[str, str]
    iface_out: dict[str, str]
    nodes: dict[str, dict[str, Any]]
    links: list[dict[str, Any]]

    def interface_identifier(self, display_name: str) -> str:
        identifier = self.iface_in.get(display_name)
        if identifier is None:
            raise RecipeError(
                f"group {self.name!r} has no input named {display_name!r}; "
                f"available: {sorted(self.iface_in)}"
            )
        return identifier

    def group_input_source(self, display_name: str) -> str:
        """The Group Input node's output socket identifier for an interface input."""
        identifier = self.interface_identifier(display_name)
        for socket in self.nodes[self.node_in].get("outputs") or []:
            if socket.get("identifier") == identifier:
                return str(socket["identifier"])
        raise RecipeError(
            f"Group Input node {self.node_in!r} has no output socket with identifier {identifier!r} "
            f"(interface input {display_name!r}); the node and the interface disagree"
        )

    def group_output_target(self, display_name: str) -> str:
        """The Group Output node's input socket identifier for an interface output."""
        identifier = self.iface_out.get(display_name)
        for socket in self.nodes[self.node_out].get("inputs") or []:
            if socket.get("name") == display_name or (
                identifier is not None and socket.get("identifier") == identifier
            ):
                return str(socket["identifier"])
        raise RecipeError(
            f"Group Output node {self.node_out!r} has no input socket for output {display_name!r}"
        )

    def join_input_links(self, join_node: str, join_socket: str) -> list[dict[str, Any]]:
        return [
            link for link in self.links
            if link.get("to_node") == join_node and link.get("to_socket") == join_socket
        ]

    def require_nodes(self, names: Sequence[str], phase: str) -> None:
        missing = [name for name in names if name not in self.nodes]
        if missing:
            raise RecipeError(
                f"phase {phase!r} needs node(s) {missing} in group {self.name!r}, which are missing. "
                f"Run the earlier phases in order: inspect -> seat -> legs -> back."
            )


def build_group_view(payload: dict[str, Any]) -> GroupView:
    nodes: dict[str, dict[str, Any]] = {}
    for node in payload.get("nodes") or []:
        name = node.get("name")
        if isinstance(name, str):
            nodes[name] = node
    node_in = next((n for n, node in nodes.items() if node.get("bl_idname") == "NodeGroupInput"), None)
    node_out = next((n for n, node in nodes.items() if node.get("bl_idname") == "NodeGroupOutput"), None)
    if node_in is None or node_out is None:
        raise RecipeError(
            "the node group has no Group Input / Group Output node; the typed creation tool always "
            "creates both, so this group was probably built by hand"
        )
    interface = payload.get("interface") or {}
    iface_in = {i["name"]: i["identifier"] for i in interface.get("inputs") or [] if "name" in i}
    iface_out = {i["name"]: i["identifier"] for i in interface.get("outputs") or [] if "name" in i}
    return GroupView(
        name=str(payload.get("name") or ""),
        node_in=node_in,
        node_out=node_out,
        iface_in=iface_in,
        iface_out=iface_out,
        nodes=nodes,
        links=list(payload.get("links") or []),
    )


class Sockets:
    """Socket identifiers shared by every node of a given type."""

    def __init__(self, discovery: Discovery, group: GroupView) -> None:
        self.group = group
        self.cube_size = discovery.input(NT_CUBE, "Size")
        self.cube_mesh = discovery.output(NT_CUBE, "Mesh")
        self.xform_geometry_in = discovery.input(NT_TRANSFORM, "Geometry")
        self.xform_geometry_out = discovery.output(NT_TRANSFORM, "Geometry")
        self.xform_translation = discovery.input(NT_TRANSFORM, "Translation")
        self.xform_rotation = discovery.input(NT_TRANSFORM, "Rotation")
        self.xform_scale = discovery.input(NT_TRANSFORM, "Scale")
        self.join_geometry_in = discovery.input(NT_JOIN, "Geometry")
        self.join_geometry_out = discovery.output(NT_JOIN, "Geometry")
        self.xyz_x = discovery.input(NT_COMBINE, "X")
        self.xyz_y = discovery.input(NT_COMBINE, "Y")
        self.xyz_z = discovery.input(NT_COMBINE, "Z")
        self.xyz_vector = discovery.output(NT_COMBINE, "Vector")
        # ShaderNodeMath exposes three inputs that all *display* as "Value"; the
        # operands are therefore addressed by the identifiers discovered at these
        # indices (never by display name).
        self.math_a = str(discovery.input_by_index(NT_MATH, 0)["identifier"])
        self.math_b = str(discovery.input_by_index(NT_MATH, 1)["identifier"])
        self.math_out = discovery.output(NT_MATH, "Value")
        self.group_out_geometry = group.group_output_target("Geometry")

    def source(self, display_name: str) -> Source:
        """(node, socket) of a Group Input output for an interface input."""
        return (self.group.node_in, self.group.group_input_source(display_name))


